#!/usr/bin/env python3
"""Generate the MQTT blueprint from the webhook blueprint, so the two never drift apart.

    python3 scripts/build_blueprints.py          # (re)write music_light_synk_mqtt.yaml
    python3 scripts/build_blueprints.py --check  # CI: fail if the generated file is stale

Edit only home-assistant/blueprints/automation/music_light_synk.yaml.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "home-assistant/blueprints/automation/music_light_synk.yaml"
DST = ROOT / "home-assistant/blueprints/automation/music_light_synk_mqtt.yaml"

REPLACEMENTS = [
    (
        "  name: Music Light Synk - album art colours to lights\n",
        "  name: Music Light Synk (MQTT) - album art colours to lights\n",
    ),
    (
        "    Works with the **Music Light Synk** TV app. The app sends **one webhook per track change**\n"
        "    (not a continuous stream), so even slow cloud bulbs such as Tuya keep up.\n",
        "    Works with the **Music Light Synk** TV app with **MQTT** turned on. The app publishes\n"
        "    **one MQTT message per track change** (not a continuous stream), so even slow cloud\n"
        "    bulbs such as Tuya keep up. Needs Home Assistant's MQTT integration.\n",
    ),
    (
        "/blob/main/home-assistant/blueprints/automation/music_light_synk.yaml\n",
        "/blob/main/home-assistant/blueprints/automation/music_light_synk_mqtt.yaml\n",
    ),
    (
        "    webhook_id:\n"
        "      name: Webhook ID\n"
        "      description: >-\n"
        "        Must match \"Webhook ID\" in the TV app. Anyone on your network who knows it can\n"
        "        change your lights, so pick something unguessable if that matters to you.\n"
        "      default: music_light_synk\n"
        "      selector:\n"
        "        text: {}\n",
        "    mqtt_topic:\n"
        "      name: MQTT event topic\n"
        "      description: >-\n"
        "        The app's topic prefix + \"/event\". Default prefix is music_light_synk; use a\n"
        "        different prefix per TV, e.g. music_light_synk/bedroom/event.\n"
        "      default: music_light_synk/event\n"
        "      selector:\n"
        "        text: {}\n",
    ),
    (
        "triggers:\n"
        "  - trigger: webhook\n"
        "    webhook_id: !input webhook_id\n"
        "    allowed_methods:\n"
        "      - POST\n"
        "    local_only: true\n",
        "triggers:\n"
        "  - trigger: mqtt\n"
        "    topic: !input mqtt_topic\n",
    ),
    (
        "  payload: \"{{ trigger.json if (trigger.json is defined and trigger.json is mapping) else {} }}\"\n",
        "  payload: \"{{ trigger.payload_json if (trigger.payload_json is defined and trigger.payload_json is mapping) else {} }}\"\n",
    ),
]

HEADER = (
    "# GENERATED by scripts/build_blueprints.py from music_light_synk.yaml - do not edit by hand.\n"
)


def build() -> str:
    text = SRC.read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if text.count(old) != 1:
            raise SystemExit(f"build_blueprints: expected exactly one occurrence of:\n{old}")
        text = text.replace(old, new)
    return HEADER + text


def main() -> int:
    out = build()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text(encoding="utf-8") != out:
            print(f"{DST.relative_to(ROOT)} is stale: run python3 scripts/build_blueprints.py")
            return 1
        print(f"OK: {DST.relative_to(ROOT)} is up to date")
        return 0
    DST.write_text(out, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
